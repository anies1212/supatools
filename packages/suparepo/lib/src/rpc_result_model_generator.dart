import 'package:recase/recase.dart';
import 'package:supabase_schema_core/supabase_schema_core.dart';

/// Generates Freezed result model classes for RETURNS TABLE
/// RPC functions.
class RpcResultModelGenerator {
  /// Returns the Dart class name for a function's result model.
  ///
  /// e.g. `get_my_invite_code` → `GetMyInviteCodeResult`
  static String resultClassName(String functionName) {
    return '${ReCase(functionName).pascalCase}Result';
  }

  /// Returns the file name (without directory) for a result model.
  ///
  /// e.g. `get_my_invite_code` → `get_my_invite_code_result.dart`
  static String resultFileName(String functionName) {
    return '${functionName}_result.dart';
  }

  /// Generates a single Freezed result model file for the given
  /// [RpcFunctionInfo] that has non-null [tableColumns].
  ///
  /// Returns `null` if the function has no tableColumns.
  String? generateResultModel(RpcFunctionInfo func) {
    final columns = func.tableColumns;
    if (columns == null || columns.isEmpty) return null;

    final className = resultClassName(func.name);
    final freezedPart = '${func.name}_result.freezed.dart';

    final buffer = StringBuffer();

    // Header
    buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
    buffer.writeln('// Generated by suparepo');
    buffer.writeln(
      '// ignore_for_file: type=lint',
    );
    buffer.writeln(
      '// ignore_for_file: public_member_api_docs, '
      'sort_constructors_first, lines_longer_than_80_chars',
    );
    buffer.writeln();

    // Imports
    buffer.writeln(
      "import 'package:freezed_annotation/freezed_annotation.dart';",
    );
    final hasErrorType = func.errorCodes != null && func.errorCodes!.isNotEmpty;
    if (hasErrorType) {
      buffer.writeln("import '${errorFileName(func.name)}';");
    }
    buffer.writeln();
    buffer.writeln("part '$freezedPart';");
    buffer.writeln();

    // Doc comment
    buffer.writeln('/// Response model for `${func.name}` RPC.');

    // Class
    buffer.writeln('@freezed');
    buffer.writeln(
      'abstract class $className with _\$$className {',
    );
    buffer.writeln('  const factory $className({');

    final errClassName = hasErrorType ? errorClassName(func.name) : null;

    for (final col in columns) {
      final fieldName = ReCase(col.name).camelCase;
      final isErrorCol =
          hasErrorType && (col.name == 'error' || col.name == 'error_code');
      final hasNested =
          col.nestedColumns != null && col.nestedColumns!.isNotEmpty;
      final String dartType;
      if (isErrorCol) {
        dartType = errClassName!;
      } else if (hasNested) {
        final nestedName = _nestedClassName(className, col.name);
        dartType = col.isArray ? 'List<$nestedName>' : nestedName;
      } else if (TypeMapper.isJsonType(col.dataType)) {
        dartType = 'dynamic';
      } else {
        dartType = TypeMapper.mapType(col.dataType);
      }
      buffer.writeln('    required $dartType $fieldName,');
    }

    buffer.writeln('  }) = _$className;');
    buffer.writeln();

    // fromRow factory
    buffer.writeln(
      '  factory $className.fromRow('
      'Map<String, dynamic> row) =>',
    );
    buffer.writeln('      $className(');

    for (final col in columns) {
      final fieldName = ReCase(col.name).camelCase;
      final isErrorCol =
          hasErrorType && (col.name == 'error' || col.name == 'error_code');
      final isJson = TypeMapper.isJsonType(col.dataType);
      final hasNested =
          col.nestedColumns != null && col.nestedColumns!.isNotEmpty;
      if (isErrorCol) {
        buffer.writeln(
          "        $fieldName: "
          "$errClassName.fromErrorCode("
          "row['${col.name}'] as String),",
        );
      } else if (hasNested) {
        final nestedName = _nestedClassName(className, col.name);
        if (col.isArray) {
          buffer.writeln(
            "        $fieldName: "
            "(row['${col.name}'] as List<dynamic>)",
          );
          buffer.writeln(
            "            .map((e) => $nestedName.fromRow("
            "e as Map<String, dynamic>))",
          );
          buffer.writeln('            .toList(),');
        } else {
          buffer.writeln(
            "        $fieldName: $nestedName.fromRow("
            "row['${col.name}'] as Map<String, dynamic>),",
          );
        }
      } else if (isJson) {
        buffer.writeln(
          "        $fieldName: row['${col.name}'],",
        );
      } else {
        final dartType = TypeMapper.mapType(col.dataType);
        if (dartType == 'DateTime') {
          buffer.writeln(
            "        $fieldName: "
            "DateTime.parse(row['${col.name}'] as String),",
          );
        } else {
          buffer.writeln(
            "        $fieldName: row['${col.name}'] as $dartType,",
          );
        }
      }
    }

    buffer.writeln('      );');
    buffer.writeln('}');

    // Generate nested model classes in the same file
    for (final col in columns) {
      if (col.nestedColumns == null || col.nestedColumns!.isEmpty) {
        continue;
      }
      buffer.writeln();
      _generateNestedClass(
        buffer,
        _nestedClassName(className, col.name),
        col.nestedColumns!,
      );
    }

    return buffer.toString();
  }

  /// Returns the class name for a nested json column model.
  static String _nestedClassName(
    String parentClass,
    String columnName,
  ) {
    return '$parentClass${ReCase(columnName).pascalCase}Item';
  }

  /// Generates a nested Freezed class for a json column.
  void _generateNestedClass(
    StringBuffer buffer,
    String className,
    List<RpcTableColumn> columns,
  ) {
    buffer.writeln('/// Nested model for json column.');
    buffer.writeln('@freezed');
    buffer.writeln(
      'abstract class $className with _\$$className {',
    );
    buffer.writeln('  const factory $className({');

    for (final col in columns) {
      final fieldName = ReCase(col.name).camelCase;
      final dartType = TypeMapper.mapType(col.dataType);
      buffer.writeln('    required $dartType $fieldName,');
    }

    buffer.writeln('  }) = _$className;');
    buffer.writeln();

    // fromRow factory
    buffer.writeln(
      '  factory $className.fromRow('
      'Map<String, dynamic> row) =>',
    );
    buffer.writeln('      $className(');

    for (final col in columns) {
      final fieldName = ReCase(col.name).camelCase;
      final dartType = TypeMapper.mapType(col.dataType);
      if (dartType == 'DateTime') {
        buffer.writeln(
          "        $fieldName: "
          "DateTime.parse(row['${col.name}'] as String),",
        );
      } else {
        buffer.writeln(
          "        $fieldName: row['${col.name}'] as $dartType,",
        );
      }
    }

    buffer.writeln('      );');
    buffer.writeln('}');
  }

  /// Generates all result model files for the given functions.
  ///
  /// Returns a map of file name → file content for functions
  /// that have [tableColumns].
  Map<String, String> generateAllResultModels(
    List<RpcFunctionInfo> functions,
  ) {
    final result = <String, String>{};

    for (final func in functions) {
      final content = generateResultModel(func);
      if (content != null) {
        result[resultFileName(func.name)] = content;
      }
    }

    return result;
  }

  /// Returns the class name for a function's error type.
  static String errorClassName(String functionName) {
    return '${ReCase(functionName).pascalCase}Error';
  }

  /// Returns the file name for an error type.
  static String errorFileName(String functionName) {
    return '${functionName}_error.dart';
  }

  /// Generates a Freezed sealed error class for an RPC function
  /// that has detected error codes.
  ///
  /// Returns `null` if the function has no error codes.
  String? generateErrorClass(RpcFunctionInfo func) {
    final codes = func.errorCodes;
    if (codes == null || codes.isEmpty) return null;

    final className = errorClassName(func.name);
    final freezedPart = '${func.name}_error.freezed.dart';

    final buffer = StringBuffer();

    // Header
    buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
    buffer.writeln('// Generated by suparepo');
    buffer.writeln(
      '// ignore_for_file: type=lint',
    );
    buffer.writeln(
      '// ignore_for_file: public_member_api_docs, '
      'sort_constructors_first, lines_longer_than_80_chars',
    );
    buffer.writeln();

    // Imports
    buffer.writeln(
      "import 'package:freezed_annotation/freezed_annotation.dart';",
    );
    buffer.writeln();
    buffer.writeln("part '$freezedPart';");
    buffer.writeln();

    // Doc comment
    buffer.writeln('/// Error code type for `${func.name}` RPC.');

    // Sealed class
    buffer.writeln('@freezed');
    buffer.writeln(
      'sealed class $className with _\$$className {',
    );
    buffer.writeln('  const $className._();');
    buffer.writeln();

    // Named constructors for each error code
    for (final code in codes) {
      final factoryName = ReCase(code).camelCase;
      final subclassName = '$className${ReCase(code).pascalCase}';
      buffer.writeln(
        '  const factory $className.$factoryName()'
        ' = $subclassName;',
      );
    }

    // Unknown variant
    buffer.writeln();
    buffer.writeln(
      '  const factory $className.unknown({',
    );
    buffer.writeln('    required String code,');
    buffer.writeln('  }) = ${className}Unknown;');
    buffer.writeln();

    // fromErrorCode factory
    buffer.writeln(
      '  factory $className.fromErrorCode('
      'String code) {',
    );
    buffer.writeln('    return switch (code) {');

    for (final code in codes) {
      final factoryName = ReCase(code).camelCase;
      buffer.writeln(
        "      '$code' => $className.$factoryName(),",
      );
    }

    buffer.writeln(
      '      _ => $className.unknown(code: code),',
    );
    buffer.writeln('    };');
    buffer.writeln('  }');

    buffer.writeln('}');

    return buffer.toString();
  }

  /// Generates all error class files for the given functions.
  ///
  /// Returns a map of file name → file content for functions
  /// that have [errorCodes].
  Map<String, String> generateAllErrorClasses(
    List<RpcFunctionInfo> functions,
  ) {
    final result = <String, String>{};

    for (final func in functions) {
      final content = generateErrorClass(func);
      if (content != null) {
        result[errorFileName(func.name)] = content;
      }
    }

    return result;
  }
}
